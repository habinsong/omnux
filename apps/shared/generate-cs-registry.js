#!/usr/bin/env node
/**
 * model-registry.json → C# ModelRegistry.cs 코드젠.
 * 미들웨어 빌드 전에 실행하면 C#이 항상 최신 모델 레지스트리를 사용.
 *
 * 사용: node apps/shared/generate-cs-registry.js
 */
const fs = require("fs");
const path = require("path");

const registryPath = path.join(__dirname, "model-registry.json");
const outputPath = path.join(__dirname, "..", "omnux-middleware", "src", "ModelRegistry.cs");
const capabilityOutputPath = path.join(__dirname, "..", "omnux-middleware", "src", "ProviderCapabilityRegistry.cs");

const registry = JSON.parse(fs.readFileSync(registryPath, "utf8"));
const providers = registry.providers;

function csStringArray(arr) {
  return `new[] { ${arr.map((s) => `"${s}"`).join(", ")} }`;
}

function csProviderKey(key) {
  return `"${key}"`;
}

let cs = `// <auto-generated by generate-cs-registry.js>
#nullable enable
using System.Collections.Frozen;

namespace Omnux.Middleware;

public sealed record CopilotModelMeta(string Provider, string PremiumMultiplier);

public static class ModelRegistry
{
    public static string GetDefaultModel(string provider)
        => Defaults.TryGetValue(provider, out var model) ? model : "unknown";

    public static string GetWorkerDefault(string provider)
        => WorkerDefaults.TryGetValue(provider, out var model) ? model : "none";

    public static IReadOnlyList<string> GetFallbackModels(string provider)
        => Fallbacks.TryGetValue(provider, out var list) ? list : Array.Empty<string>();

    public static string GetLabel(string provider)
        => Labels.TryGetValue(provider, out var label) ? label : provider;

    public static CopilotModelMeta? GetCopilotKnownMeta(string modelId)
        => CopilotKnownMeta.TryGetValue(modelId, out var meta) ? meta : null;
`;

// Defaults
const defaultEntries = Object.entries(providers).map(([k, v]) => `    [${csProviderKey(k)}] = "${v.default}"`);
cs += `    private static readonly FrozenDictionary<string, string> Defaults = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)\n    {\n${defaultEntries.join(",\n")}\n    }.ToFrozenDictionary();\n\n`;

// WorkerDefaults
const workerEntries = Object.entries(providers).map(([k, v]) => `    [${csProviderKey(k)}] = "${v.workerDefault}"`);
cs += `    private static readonly FrozenDictionary<string, string> WorkerDefaults = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)\n    {\n${workerEntries.join(",\n")}\n    }.ToFrozenDictionary();\n\n`;

// Labels
const labelEntries = Object.entries(providers).map(([k, v]) => `    [${csProviderKey(k)}] = "${v.label}"`);
cs += `    private static readonly FrozenDictionary<string, string> Labels = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)\n    {\n${labelEntries.join(",\n")}\n    }.ToFrozenDictionary();\n\n`;

// Fallbacks
const fallbackEntries = Object.entries(providers).map(([k, v]) => `    [${csProviderKey(k)}] = ${csStringArray(v.fallback)}`);
cs += `    private static readonly FrozenDictionary<string, string[]> Fallbacks = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase)\n    {\n${fallbackEntries.join(",\n")}\n    }.ToFrozenDictionary();\n\n`;

const copilotMeta = providers.copilot.knownMeta || {};
if (Object.keys(copilotMeta).length > 0) {
  const metaEntries = Object.entries(copilotMeta).map(([k, v]) => `    ["${k}"] = new("${v.owner}", "${v.costMultiplier}")`);
  cs += `    public static readonly FrozenDictionary<string, CopilotModelMeta> CopilotKnownMeta = new Dictionary<string, CopilotModelMeta>(StringComparer.OrdinalIgnoreCase)\n    {\n${metaEntries.join(",\n")}\n    }.ToFrozenDictionary();\n`;;
}
cs += `}\n`;

// ── 제공자/모델별 능력(네이티브 웹 검색·추론 강도) ──
// 같은 JSON 한 곳에서 UI(TS)와 미들웨어(C#)가 같은 표를 읽게 만든다.
// 약어는 C# 관례대로 읽히도록 따로 적는다 (openai → OpenAi).
const ENUM_WORD_OVERRIDES = { openai: "OpenAi", cli: "Cli", nvidia: "Nvidia" };

function csEnumMember(value) {
  return value
    .split(/[_\-\s]+/)
    .filter(Boolean)
    .map((part) => ENUM_WORD_OVERRIDES[part] || part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

const capabilities = registry.capabilities || { providers: {}, webSearchModes: [], reasoningModes: [] };
const webSearchModes = capabilities.webSearchModes || [];
const reasoningModes = capabilities.reasoningModes || [];

const capabilityRuleEntries = Object.entries(capabilities.providers || {}).map(([provider, rules]) => {
  const items = rules
    .map((rule) => {
      const levels = (rule.levels || []).length > 0 ? csStringArray(rule.levels) : "Array.Empty<string>()";
      const defaultLevel = rule.defaultLevel || (rule.levels && rule.levels.length ? rule.levels[0] : "");
      return `        new ProviderCapabilityRule("${rule.match.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}", ProviderWebSearchMode.${csEnumMember(rule.webSearch)}, ProviderReasoningMode.${csEnumMember(rule.reasoning)}, ${levels}, "${defaultLevel}")`;
    })
    .join(",\n");
  return `    ["${provider}"] = new ProviderCapabilityRule[]\n    {\n${items}\n    }`;
});

let capabilityCs = `// <auto-generated by generate-cs-registry.js>
#nullable enable
using System.Collections.Frozen;
using System.Text.RegularExpressions;

namespace Omnux.Middleware;

/// <summary>제공자가 서버측에서 직접 수행하는 웹 검색 방식. None 이면 외부 retriever 로 근거를 모아 넣는다.</summary>
public enum ProviderWebSearchMode
{
${webSearchModes.map((mode) => `    ${csEnumMember(mode)}`).join(",\n")}
}

/// <summary>추론 강도를 요청에 싣는 방식. 제공자마다 파라미터 이름과 허용값이 다르다.</summary>
public enum ProviderReasoningMode
{
${reasoningModes.map((mode) => `    ${csEnumMember(mode)}`).join(",\n")}
}

public sealed record ProviderCapabilityRule(
    string Match,
    ProviderWebSearchMode WebSearch,
    ProviderReasoningMode Reasoning,
    string[] Levels,
    string DefaultLevel
);

public sealed record ProviderCapability(
    string Provider,
    string Model,
    ProviderWebSearchMode WebSearch,
    ProviderReasoningMode Reasoning,
    IReadOnlyList<string> ReasoningLevels,
    string DefaultReasoningLevel
)
{
    public bool SupportsNativeWebSearch => WebSearch != ProviderWebSearchMode.None;

    public bool SupportsReasoningControl => Reasoning != ProviderReasoningMode.None && ReasoningLevels.Count > 0;

    /// <summary>요청받은 강도를 이 모델이 실제로 받는 값으로 좁힌다. 못 받으면 빈 문자열.</summary>
    public string NormalizeReasoningLevel(string? requested)
    {
        if (!SupportsReasoningControl)
        {
            return string.Empty;
        }

        var normalized = (requested ?? string.Empty).Trim().ToLowerInvariant();
        if (normalized.Length == 0 || normalized == "auto")
        {
            return DefaultReasoningLevel;
        }

        foreach (var level in ReasoningLevels)
        {
            if (string.Equals(level, normalized, StringComparison.OrdinalIgnoreCase))
            {
                return level;
            }
        }

        // 모델이 지원하지 않는 단계는 가장 가까운 단계로 내린다("minimal" 없는 모델의 minimal → low).
        var order = new[] { "off", "minimal", "low", "medium", "high" };
        var requestedIndex = Array.IndexOf(order, normalized);
        if (requestedIndex < 0)
        {
            return DefaultReasoningLevel;
        }

        var best = DefaultReasoningLevel;
        var bestDistance = int.MaxValue;
        foreach (var level in ReasoningLevels)
        {
            var index = Array.IndexOf(order, level.ToLowerInvariant());
            if (index < 0)
            {
                continue;
            }

            var distance = Math.Abs(index - requestedIndex);
            if (distance < bestDistance)
            {
                bestDistance = distance;
                best = level;
            }
        }

        return best;
    }
}

public static class ProviderCapabilityRegistry
{
    private static readonly FrozenDictionary<string, ProviderCapabilityRule[]> Rules = new Dictionary<string, ProviderCapabilityRule[]>(StringComparer.OrdinalIgnoreCase)
    {
${capabilityRuleEntries.join(",\n")}
    }.ToFrozenDictionary();

    private static readonly ProviderCapability Unknown = new(
        string.Empty,
        string.Empty,
        ProviderWebSearchMode.None,
        ProviderReasoningMode.None,
        Array.Empty<string>(),
        string.Empty
    );

    public static ProviderCapability Resolve(string? provider, string? model)
    {
        var providerKey = (provider ?? string.Empty).Trim();
        var modelId = (model ?? string.Empty).Trim();
        if (providerKey.Length == 0 || !Rules.TryGetValue(providerKey, out var rules))
        {
            return Unknown with { Provider = providerKey, Model = modelId };
        }

        if (modelId.Length == 0)
        {
            modelId = ModelRegistry.GetDefaultModel(providerKey);
        }

        foreach (var rule in rules)
        {
            if (!Regex.IsMatch(modelId, rule.Match, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant))
            {
                continue;
            }

            return new ProviderCapability(
                providerKey,
                modelId,
                rule.WebSearch,
                rule.Reasoning,
                rule.Levels,
                rule.DefaultLevel
            );
        }

        return Unknown with { Provider = providerKey, Model = modelId };
    }

    /// <summary>이 제공자에서 네이티브 웹 검색이 되는 모델 목록(fallback 카탈로그 기준).</summary>
    public static IReadOnlyList<string> ListNativeWebSearchModels(string provider)
    {
        return ModelRegistry.GetFallbackModels(provider)
            .Where(model => Resolve(provider, model).SupportsNativeWebSearch)
            .ToArray();
    }
}
`;

if (process.argv.includes("--check")) {
  const mismatched = [];
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== cs) {
    mismatched.push(outputPath);
  }
  if (!fs.existsSync(capabilityOutputPath) || fs.readFileSync(capabilityOutputPath, "utf8") !== capabilityCs) {
    mismatched.push(capabilityOutputPath);
  }
  if (mismatched.length > 0) {
    console.error("모델 레지스트리가 일치하지 않습니다. node apps/shared/generate-cs-registry.js를 실행하세요.");
    console.error(mismatched.join("\n"));
    process.exit(1);
  }
  console.log("모델 레지스트리 동기화 확인 완료");
} else {
  fs.writeFileSync(outputPath, cs, "utf8");
  fs.writeFileSync(capabilityOutputPath, capabilityCs, "utf8");
  console.log(`Generated: ${outputPath}`);
  console.log(`Generated: ${capabilityOutputPath}`);
}
